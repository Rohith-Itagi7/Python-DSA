x = 3
y = 9

# addition operator
print(x + y)

# subtraction operator
print(x - y)

# division operator
print(x / y)

# floor division operator
print(x // y)

# multiplication operator
print(x * y)

# modulo operator
print(x % y)

# power operator
print(x ** y)

# Comparison Operators in Python
x = 3
y = 9

# less than operator
print(x < y)

# greater than operator
print(x > y)

# equals to operator
print(x == y)

# not equals to operator
print(x != y)

# greater than or equal to operator
print(x >= y)

# less than or equal to operator
print(x <= y)
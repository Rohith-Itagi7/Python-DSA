#using +
v1 = "Coding "
v2 = "Ninjas"
v3=v1+v2
print(v3)

#using join()
v1 = "Coding "
v2 = "Ninjas"
v3=" ".join([v1,v2])
print(v3)

# using %
v1 = "Coding "
v2 = "Ninjas"
v3="%s %s" %(v1,v2)
print(v3)

#using format
v1 = "Coding"
v2 = "Ninjas"
print("{} {}".format(v1,v2))

# using comma
v1 = "Coding"
v2 = "Ninjas"
print(v1, v2)